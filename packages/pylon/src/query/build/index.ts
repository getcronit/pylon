export interface GenerateClientOptions {
  /** GraphQL scalar name → TS type. */
  scalarTypes?: Record<string, string>
  /** Override the GraphQL endpoint baked into the generated client. */
  endpoint?: string
}

export interface GeneratedClientFiles {
  /** `.pylon/client/index.ts` — the runtime client + descriptor. */
  indexTs: string
  /** `.pylon/client/types.ts` — the authoring `Data` root type. */
  typesTs: string
}

/**
 * Produce the generated client sources for a schema. `pylon-dev`'s
 * `build-client.ts` writes these to `.pylon/client/`. This replaces gqty's
 * `generateClient`.
 */
export function generateClientFiles(
  sdl: string | GraphQLSchema,
  options: GenerateClientOptions = {}
): GeneratedClientFiles {
  const schema = typeof sdl === 'string' ? buildSchema(sdl) : sdl
  const descriptor = describeSchema(schema)
  const typesTs = generateRootType(schema, options.scalarTypes)

  const endpoint = options.endpoint ?? '/graphql'
  const indexTs = `/**
 * Generated by @getcronit/pylon/query. Safe to read; regenerated on build.
 */
import {createPylonQueryClient, registerOperationClient, type SchemaDescriptor} from '@getcronit/pylon/query'
import type {Data} from './types'

export const descriptor: SchemaDescriptor = ${JSON.stringify(descriptor)}

const options = {endpoint: ${JSON.stringify(endpoint)}, descriptor}

/** Shared browser client (singleton). */
export const client = createPylonQueryClient(options)

// Imperative \`op.query\`/\`op.mutation\` run against this client (browser only).
if (typeof window !== 'undefined') registerOperationClient(client)

/** Fresh per-request client for SSR (isolated store per request). */
export const createPagesClient = () => createPylonQueryClient(options)

export type {Data}
export * from './types'
`

  return {indexTs, typesTs}
}
